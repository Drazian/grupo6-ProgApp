    private void cargarProgramas(){
        try{
            IControlador ic = Fabrica.getInstance().getIControlador();
            List<DtPrograma> lista = ic.listarProgramas();
            cbPrograma.removeAllItems();
            for (DtPrograma aux : lista){
                cbPrograma.addItem(aux.getNombre());
            }
        
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al obtener lista de Programas de Formacion: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void cargarCursos(){
        try{
            txtCurso.setText(""); 
            
            IControlador ic = Fabrica.getInstance().getIControlador();
            List<DtCurso> lista = ic.listarCursos();
            DefaultTableModel model = (DefaultTableModel) tbl.getModel();
            model.setRowCount(0);
            for (DtCurso aux: lista){
                String strPrevias = (aux.getPrevias_toArray() != null && !aux.getPrevias_toArray().isEmpty()) 
                                        ? String.join(", ", aux.getPrevias_toArray()) 
                                        : "---";
                
                String strCategorias = (aux.getCategorias_toArray() != null && !aux.getCategorias_toArray().isEmpty()) 
                                        ? String.join(", ", aux.getCategorias_toArray()) 
                                        : "---";
                
                model.addRow(new Object[]{
                        aux.getNombre(),
                        aux.getDescripcion(),
                        aux.getDuracion(),
                        aux.getCantidadHoras(),
                        aux.getCreditos(),
                        aux.getFechaRegistro(),
                        aux.getUrl(),
                        strPrevias,
                        strCategorias
                    });   
            }
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al obtener Cursos: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
        
    }
    
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try{
            
            if (cbPrograma.getItemCount() <= 0 || cbPrograma.getSelectedItem() == null){
                JOptionPane.showMessageDialog(this, "No hay programas de formación disponibles.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            String programa = cbPrograma.getSelectedItem().toString();
            String curso = txtCurso.getText().trim();
        
            if (curso.isEmpty()||programa.isEmpty()){
                JOptionPane.showMessageDialog(this, "Debe seleccionar un curso y un Programa de Formacion validos", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            IControlador ic = Fabrica.getInstance().getIControlador();
            ic.agregarProgramaCurso(programa, curso);
            
            JOptionPane.showMessageDialog(this, "Curso '"+curso+"' agregado con éxito al programa de formacion '"+programa+"'.","Éxito",JOptionPane.INFORMATION_MESSAGE);

        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al agregar curso a programa de formacion: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnAgregarActionPerformed

