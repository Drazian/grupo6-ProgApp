    private boolean isChanged(){
        boolean flag=false;
        if(!Utils.Validate.isEmpty(jTnombre.getText())) flag=true;
        if(!Utils.Validate.isEmpty(jTAdescripcion.getText())) flag=true;
        if(fechaInicio!=null) flag=true;
        if(fechaFin!=null) flag=true;
        if(fechaRegistro!=null) flag=true;
        return flag;
    }
    
    private void jTnombre(){
        if(jTnombre.getText().isEmpty()) reloj.alarm(true, "Nombre faltante");
        else{
            reloj.alarm(false, "Nombre faltante");
            if(Values.isExist(jTnombre.getText())){
                reloj.alarm(true, "Nombre Existente");
                jTnombre.requestFocus();
                jTnombre.setSelectionStart(0);
            }else reloj.alarm(false, "Nombre Existente");
        }
    }

    private boolean fechaValidate(String tmpFecha, String mensaje){
        boolean ret=Utils.Fecha.validate(tmpFecha);
        if(!ret) reloj.alarm(true, mensaje);
        else reloj.alarm(false, mensaje);
        return ret;
    }

    private boolean fechaValidate(LocalDate fecha1, LocalDate fecha2, JFormattedTextField obj, int modo){
        boolean flag=true;
        if(fecha1!=null){
            if(fecha2!=null)
                if(modo==IZQ_DER){
                    flag=Utils.Fecha.isCoherente(fecha1, fecha2);
                }else if(modo==DER_IZQ){
                    flag=Utils.Fecha.isCoherente(fecha2, fecha1);
                }
            obj.setText(Utils.Fecha.assignFormato(fecha1));
            if(flag) reloj.alarm(false, "Fechas Invertidas");
            else reloj.alarm(true, "Fechas Invertidas");
            
        }
        return flag;
    }

    private void resize(int modo){
        if(modo==FORMCHICO){
            jPNuevo.setVisible(false);
        }else{
            jBNew.setEnabled(false);
            jPNuevo.setVisible(true);
            reloj.enabled(true);
        }
        Utils.GUI.reSizePadre(this, formWidht[modo], formHeight);
    }
    
    private void refresh(){
        if((nombre!=null) && (fechaInicio!=null) && (fechaFin!=null)
        && (fechaRegistro!=null) && (reloj.getLista().length==0))
            jBCreate.setEnabled(true);
        else jBCreate.setEnabled(false);
        
    }
    
    private int confirm(String mensaje){
        return JOptionPane.showOptionDialog(
                this, mensaje, "Confirme acción", 
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE, null, null, null);
    }
    
