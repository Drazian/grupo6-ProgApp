    private void cbProgramaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbProgramaActionPerformed
        try{            
            //TODO: cargar labels
            if (cbPrograma.getItemCount() < 0){
            //Si no hay ningun programa creado, no hay nada que cargar.
            return;
            }
            
            if (cbPrograma.getSelectedItem() == null){
                //Validamos que haya un item seleccionado.
                return;
            }
            
            IControlador ic = Fabrica.getInstance().getIControlador();
            String programa = cbPrograma.getSelectedItem().toString();
            DtPrograma aux = ic.buscarPrograma(programa);
            txtNombre.setText(aux.getNombre());
            txaDescripcion.setText(aux.getDescripcion());
            txtRegistro.setText(Utils.Fecha.assignFormato(aux.getFechaRegistro()));
            txtInicio.setText(Utils.Fecha.assignFormato(aux.getFechaInicio()));
            txtFin.setText(Utils.Fecha.assignFormato(aux.getFechaFin()));
            cargarCursos();
            
            //Para cargar categorias
            Set<String> categorias = aux.getCategorias();
            String categoriasStr = (categorias != null && !categorias.isEmpty())
                                    ? String.join(", ", categorias)
                                    : "Sin categorías";
            txtCategorias.setText(categoriasStr);
            
            
            
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al obtener los datos: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_cbProgramaActionPerformed
  
        private void cargarProgramas(){
        //TODO: cargar lista de nombres de programas.
        try{
            IControlador ic = Fabrica.getInstance().getIControlador();           
            List<DtPrograma> lista = ic.listarProgramas();
            cbPrograma.removeAllItems();
            for (DtPrograma aux : lista){
                cbPrograma.addItem(aux.getNombre());
            }
        
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al obtener lista de Programas de Formacion: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
    }
        
    private void cargarCursos(){
        try{ 
            
            if (cbPrograma.getItemCount() < 0){
                //Si no hay ningun programa creado, no hay curso asociado que cargar.
                return;
            }
                       
            if (cbPrograma.getSelectedItem() == null){
                //Validamos que haya un item seleccionado.
                return;
            }
            
            String programa = cbPrograma.getSelectedItem().toString();
            
            //TODO: cargar cursos en base al programa
            IControlador ic = Fabrica.getInstance().getIControlador();
            List<DtCurso> lista = ic.listarCursosPorPrograma(programa);
            DefaultTableModel model = (DefaultTableModel) tblCursos.getModel();
            model.setRowCount(0);
            for (DtCurso aux: lista){
                String strPrevias = (aux.getPrevias_toArray() != null && !aux.getPrevias_toArray().isEmpty()) 
                                        ? String.join(", ", aux.getPrevias_toArray()) 
                                        : "---";
                
                String strCategorias = (aux.getCategorias_toArray() != null && !aux.getCategorias_toArray().isEmpty()) 
                                        ? String.join(", ", aux.getCategorias_toArray()) 
                                        : "---";
                
                model.addRow(new Object[]{
                        aux.getNombre(),
                        aux.getDescripcion(),
                        aux.getDuracion(),
                        aux.getCantidadHoras(),
                        aux.getCreditos(),
                        aux.getFechaRegistro(),
                        aux.getUrl(),
                        strPrevias,
                        strCategorias
                    });   
            }

        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al obtener Cursos: "+e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
        
    }

    
