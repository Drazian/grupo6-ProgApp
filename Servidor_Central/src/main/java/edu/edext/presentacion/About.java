    private void leerWSDL(){
        int pos0, pos1, pos2, pos3, pos4;
        for(String tmp : Utils.Disk.loadFile(cfg.PATH_JAXWS_PROPERTIES)){
            if(tmp.contains("wsdl.url=")){
                pos0=tmp.indexOf("l=")+2;
                pos1=tmp.indexOf("//")+2;
                pos2=tmp.lastIndexOf(":")+1;
                pos3=tmp.lastIndexOf("/");
                pos4=tmp.indexOf("?wsdl");
                this.ip=tmp.substring(pos1, pos2-1);
                this.port=tmp.substring(pos2, pos3);
                this.wsdl=tmp.substring(pos0, pos4);
            }
        }
    }
    
