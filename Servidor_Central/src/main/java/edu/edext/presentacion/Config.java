    private void loadConf(){
        confDB=Utils.Disk.loadCFG(cfg.PATH_FILE);
        for(CfgDB cfgDB : confDB){
            if(cfgDB.clave().equals(cfg.CLAVE_IMAGE)){
                tmpImagen=cfgDB.valor();
                jTImagen.setText(tmpImagen); }
            else if(cfgDB.clave().equals(cfg.CLAVE_IP)){
                tmpIP=cfgDB.valor();
                jTIP.setText(tmpIP); }
            else if(cfgDB.clave().equals(cfg.CLAVE_PORT)){
                tmpPort=cfgDB.valor();
                jTPort.setText(tmpPort); }
        }
    }
    private void refreshBGuardar(){
        String imagen=jTImagen.getText().trim(), ip=jTIP.getText().trim(), puerto=jTPort.getText().trim();
        if((Utils.Validate.isEmpty(imagen) && Utils.Validate.isEmpty(ip) && Utils.Validate.isEmpty(puerto)) ||
           (imagen.equals(tmpImagen) && ip.equals(tmpIP) && puerto.equals(tmpPort)))
            jBGuardar.setEnabled(false);
        else if(!imagen.equals(tmpImagen) || !ip.equals(tmpIP) || !puerto.equals(tmpPort))
            jBGuardar.setEnabled(true);
    }
    
